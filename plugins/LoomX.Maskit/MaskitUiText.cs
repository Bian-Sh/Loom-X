    public string BuiltinName(string key) =>
        BuiltinNames.TryGetValue(key, out var name) ? name : key;

    public static MaskitUiText Resolve(string cultureName)
    {
        var normalized = (cultureName ?? string.Empty).Trim().ToLowerInvariant();
        if (normalized.StartsWith("zh-tw", StringComparison.Ordinal)
            || normalized.StartsWith("zh-hk", StringComparison.Ordinal))
            return Traditional();
        if (normalized.StartsWith("zh", StringComparison.Ordinal)) return Simplified();
        return English();
    }

